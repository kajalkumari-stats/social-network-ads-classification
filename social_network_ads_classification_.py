# 1. Train a univariate Logistic Regression (Age only)
# This finds the "clean" tipping point for Age
X = data[['Age']]
y = data['Purchased']
model = LogisticRegression()
model.fit(X, y)

# 2. Extract Coefficients to find the 50% probability point
# Logistic equation: p = 1 / (1 + exp(-(m*x + c)))
# p = 0.5 when m*x + c = 0 => x = -c / m
intercept = model.intercept_[0]
coefficient = model.coef_[0][0]
crossover_age = -intercept / coefficient

print(f"Intercept: {intercept:.4f}")
print(f"Coefficient for Age: {coefficient:.4f}")
print(f"Calculated Crossover Age: {crossover_age:.2f}")

# 3. Visualization
