"""# Hypothesis Testing (Statistical Analysis)

So far we built **ML models** for prediction. Here we use **statistics** to answer:
*"Do Age, Salary and Gender have a statistically significant effect on Purchased, or is it just random chance?"*

**Standard rule:** significance level `alpha = 0.05`
- `p-value < 0.05` → **Reject H0** (the effect is statistically significant)
- `p-value >= 0.05` → **Fail to reject H0** (not enough evidence)
"""

from scipy import stats
import statsmodels.api as sm

alpha = 0.05

# Group-wise data: Purchased = 0 (did not buy) vs 1 (bought)
age_0 = data.loc[data['Purchased'] == 0, 'Age']
age_1 = data.loc[data['Purchased'] == 1, 'Age']
sal_0 = data.loc[data['Purchased'] == 0, 'EstimatedSalary']
sal_1 = data.loc[data['Purchased'] == 1, 'EstimatedSalary']

print("Group sizes -> Not Purchased:", len(age_0), "| Purchased:", len(age_1))
print("Mean Age    -> Not Purchased: %.2f | Purchased: %.2f" % (age_0.mean(), age_1.mean()))
print("Mean Salary -> Not Purchased: %.0f | Purchased: %.0f" % (sal_0.mean(), sal_1.mean()))

"""## Step 1: Assumptions check (Normality + Equal Variance)

A parametric test (t-test) assumes normality and equal variance, so we check both.
- **Shapiro-Wilk:** H0 = the data is normally distributed
- **Levene:** H0 = both groups have equal variance
"""

print("--- Shapiro-Wilk (Normality) ---")
for name, grp in [("Age | Not Purchased", age_0), ("Age | Purchased", age_1),
                  ("Salary | Not Purchased", sal_0), ("Salary | Purchased", sal_1)]:
    stat, p = stats.shapiro(grp)
    print(f"{name:25s} W={stat:.4f}  p={p:.4g}  ->", "Normal" if p >= alpha else "NOT normal")

print("\n--- Levene (Equal Variance) ---")
for name, a, b in [("Age", age_0, age_1), ("Salary", sal_0, sal_1)]:
    stat, p = stats.levene(a, b)
    print(f"{name:8s} stat={stat:.4f}  p={p:.4g}  ->", "Equal variance" if p >= alpha else "Unequal variance")

"""## Step 2: Two-sample tests (Age & Salary vs Purchased)

**H0:** The mean is the same for Purchased and Not Purchased users
**H1:** The means are different

- **Welch's t-test** (`equal_var=False`) → safe choice when variances are unequal
- **Mann-Whitney U** → non-parametric backup when normality fails
- **Cohen's d** → effect size (a p-value alone is not enough; report how large the effect is)
"""

import numpy as np

def cohens_d(a, b):
    pooled = np.sqrt(((len(a)-1)*a.var(ddof=1) + (len(b)-1)*b.var(ddof=1)) / (len(a)+len(b)-2))
    return (b.mean() - a.mean()) / pooled

for feature, a, b in [("Age", age_0, age_1), ("EstimatedSalary", sal_0, sal_1)]:
    t_stat, t_p = stats.ttest_ind(a, b, equal_var=False)
    u_stat, u_p = stats.mannwhitneyu(a, b, alternative='two-sided')
    d = cohens_d(a, b)
    print(f"=== {feature} ===")
    print(f"Welch t-test   : t={t_stat:.3f}, p={t_p:.3g}  ->", "Reject H0" if t_p < alpha else "Fail to reject H0")
    print(f"Mann-Whitney U : U={u_stat:.1f}, p={u_p:.3g}  ->", "Reject H0" if u_p < alpha else "Fail to reject H0")
    print(f"Cohen's d      : {d:.3f}  (0.2 small, 0.5 medium, 0.8 large)\n")

"""## Step 3: Chi-Square Test of Independence (Gender vs Purchased)

Both variables are **categorical**, so we use chi-square instead of a t-test.

**H0:** Gender and Purchased are independent
**H1:** Gender and Purchased are dependent (related)
"""

contingency = pd.crosstab(data['Gender'], data['Purchased'])
print(contingency, "\n")

chi2, p, dof, expected = stats.chi2_contingency(contingency)
print(f"Chi2={chi2:.4f}, dof={dof}, p={p:.4g}")
print("Decision:", "Reject H0 (Gender and Purchased are related)" if p < alpha
      else "Fail to reject H0 (no significant effect of Gender found)")

# Cramer's V (effect size)
n = contingency.values.sum()
cramers_v = np.sqrt(chi2 / (n * (min(contingency.shape) - 1)))
print(f"Cramer's V (effect size): {cramers_v:.3f}")

"""## Step 4: Correlation Test

**H0:** There is no linear relationship between the feature and Purchased (correlation = 0)
Purchased is binary, so we use **point-biserial correlation**.
"""

for feature in ['Age', 'EstimatedSalary']:
    r, p = stats.pointbiserialr(data['Purchased'], data[feature])
    print(f"{feature:16s} r={r:.3f}, p={p:.3g} ->", "Significant" if p < alpha else "Not significant")

"""## Step 5: Logistic Regression ka Statistical Significance (Wald test)

`sklearn`'s LogisticRegression does not provide p-values; `statsmodels` does.

**H0 (for each coefficient):** coefficient = 0 (the feature has no effect)
- **Odds Ratio = exp(coef)** → the factor by which the odds change for a 1-unit (scaled) increase in the feature
"""

X_sm = sm.add_constant(X_train_scaled)
logit_result = sm.Logit(y_train.values, X_sm).fit(disp=False)
print(logit_result.summary(xname=['const', 'Age', 'EstimatedSalary']))

odds_ratios = np.exp(logit_result.params[1:])
print("\nOdds Ratios (per 1 std-dev increase):")
print(pd.Series(odds_ratios, index=['Age', 'EstimatedSalary']).round(3))
print("\nLikelihood Ratio test (overall model) p-value:", f"{logit_result.llr_pvalue:.3g}")

"""## Interview Summary (quick revision)

| Question | Test | Why |
|---|---|---|
| Numeric feature vs binary target (2 groups) | **Welch t-test** / Mann-Whitney U | Comparing means |
| Categorical vs categorical | **Chi-Square** | Independence check |
| Normality check | **Shapiro-Wilk** | t-test assumption |
| Equal variance check | **Levene** | Decide between Student and Welch |
| Model coefficient significance | **Wald test** (statsmodels Logit) | p-value + odds ratio |

**Interview line:** *"An ML model tells you how well you can predict; hypothesis testing tells you whether a feature's effect is statistically real or just chance."*

**Note:** A small p-value does not mean the effect is **large**. That is why we also report effect size (Cohen's d, Cramer's V).
"""